static void generate_ili23(CliState &state,string ili23_file)
{
   Logger &logger = state.context.logger();
   logger.info("");
   logger.info("generating " + ili23_file + " ...");
   logger.incNestLevel();
   output::Ili2Output ili23output(state.context.models(),logger,ili23_file,"2.3");
   if (state.modelFilter == "") {
      ili23output.visitAllModels();
   }
   else {
      ili23output.preVisit();
      for (auto m : state.context.models().models()) {
         if (m->Name == state.modelFilter) {
            ili23output.visit(m);
         }
      }
      ili23output.postVisit();
   }
   logger.decNestLevel();
   logger.info("done.");
}

