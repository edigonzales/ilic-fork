static bool compile(CliState &state,IliFile *f)
{
   Logger &logger = state.context.logger();

   if (f->getIliVersion() == "1.0") {
   }
   else if (f->getIliVersion() == "2.3") {
   }
   else if (f->getIliVersion() == "2.4") {
   }
   else {
      logger.error(f->getFilePath() + ": unsupported iliversion " + f->getIliVersion());
      logger.decNestLevel();
      abort(logger,1);
   }

   for (auto ff : state.compiledFiles) {
      if (ff == f) {
         return true;
      }
   }

   // verify if all imported models are in the same file or already compiled
   for (auto import : f->getRequiredModels()) {
      bool found = false;
      // search in same file
      for (auto model : f->getModels()) {
         if (model == import) {
            found = true;
            break;
         }
      }

      for (auto model : f->getModels()) {
         if (model == import) {
            found = true;
            break;
         }
      }

      if (!found) {
         // search in already compiled files
         for (auto model : state.compiledModels) {
            if (model == import) {
               found = true;
               break;
            }
         }
      }
      if (!found) {
         bool translationBase = false;
         for (const auto &translation : f->getTranslationModels()) {
            if (translation == import) {
               translationBase = true;
               break;
            }
         }
         if (!translationBase) return false; // not ready to compile f
      }
   }

   logger.info("");
   logger.info("compiling " + f->getFilePath() + " ...");
   logger.incNestLevel();
   int errors = logger.getErrorCount();

   // parse input
   if (f->getIliVersion() == "1.0") {
      const string source = f->source().text;
      input::parseIli1({f->getFilePath(),source,0},state.context.builder(),logger);
   }
   else {
      const string source = f->source().text;
      input::parseIli2({f->getFilePath(),source,0},state.context.builder(),logger);
   }

   state.compiledFiles.push_back(f);
   if (f->getFilePath() == "INTERLIS") {
      state.compiledModels.push_back("INTERLIS");
   }
   else {
      for (auto model : f->getModels()) {
         state.compiledModels.push_back(model);
      }
   }

   logger.decNestLevel();
   if (logger.getErrorCount() == errors) {
      logger.info(f->getFilePath() + " compiled.");
   }
   else {
      logger.info(f->getFilePath() + " compiled with errors.");
   }

   return true;

}

