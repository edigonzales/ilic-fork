StringMap parse_arguments(int argc, char* argv[])
{

   StringMap arguments;
   string key = "";
   string value = "";
   int fid = 1;

   for (int i=1;i<argc;i++) {
      string arg = argv[i];
      if (arg.find("--") == 0) {
         key = arg.substr(2);
      }
      else if (arg.find("-") == 0) {
         key = arg.substr(1);
      }
      else if (ends_with(arg,".ili")) {
         if (key != "o1" && key != "o23" && key != "o24") {
            key = "ilifile" + to_string(fid++);
         }
         value = arg;
      }
      else {
         value = arg;
      }
      if (key != "") {
         if (key == "o2") {
            key = "o23";
         }
         else if (key == "out") {
            key = "output";
         }
         else if (key == "v") {
            key = "version";
         }
         else if (key == "u") {
            key = "usage";
         }
         else if (key == "h") {
            key = "help";
         }
         else if (key == "quiet") {
            key = "silent";
         }
         else if (arg == "without-warnings") {
            key = "no_warnings";
         }
         else if (arg == "no-auto") {
            key = "no_auto";
         }
         arguments.put(key,value);
         value = "";
      }
   }

   return arguments;

}

