int main(int argc, char* argv[])
{

   if (argc >= 2 && string(argv[1]) == "--compile-json") {
      if (argc != 2) {
         cerr << "ilic: --compile-json does not accept additional arguments" << endl;
         return 2;
      }
      return compile_json();
   }

   CliState state;
   Logger &logger = state.context.logger();

   StringMap arguments = parse_arguments(argc,argv);
   check_arguments(arguments,logger);
   bool help = false;
   bool usage = false;
   bool version = false;
   bool no_auto = false;
   string output = "";
   bool ili1 = false;
   string ili1_output = "interlis1.ili";
   bool ili23 = false;
   string ili23_output = "interlis23.ili";
   bool ili24 = false;
   string ili24_output = "interlis24.ili";
   bool imd = false;
   string imd_output = "output.imd";
   bool xsd = false;
   string xsd_output = "output.xsd";
   bool gml = false;
   string gml_output = "output.gml";
   string ilidirs = "";
   bool log_silent = false;
   bool log_info = true;
   bool log_warnings = true;
   bool log_errors = true;
   bool log_debug = false;
   string log = "";
   bool gui = false;
   int success_status = 0;

   for (auto arg : arguments.getKeys()) {

      string value = arguments.get(arg);

      if (arg == "help") {
         help = true;
      }
      else if (arg == "usage") {
         usage = true;
      }
      else if (arg == "version") {
         version = true;
      }
      else if (arg == "no_auto") {
         no_auto = true;
      }
      else if (arg == "oIMD") {
         imd = true;
         if (value != "") {
            imd_output = value;
         }
      }
      else if (arg == "o1") {
         ili1 = true;
         if (value != "") {
            ili1_output = value;
         }
      }
      else if (arg == "o23") {
         ili23 = true;
         if (value != "") {
            ili23_output = value;
         }
      }
      else if (arg == "o24") {
         ili24 = true;
         if (value != "") {
            ili24_output = value;
         }
      }
      else if (arg == "oXSD") {
         xsd = true;
         if (value != "") {
            xsd_output = value;
         }
      }
      else if (arg == "oGML") {
         gml = true;
         if (value != "") {
            gml_output = value;
         }
      }
      else if (arg == "output") {
         output = value;
         imd_output = value;
         xsd_output = value;
         gml_output = value;
      }
      else if (arg == "ilidirs") {
         ilidirs = value;
      }
      else if (arg == "repositories" || arg == "models" || arg == "ili-version"
         || arg == "no-default-repositories") {
         // Repository arguments are normalized and validated together below.
      }
      else if (arg == "silent") {
         log_silent = true;
      }
      else if (arg == "no_info") {
         log_info = false;
      }
      else if (arg == "no_warnings") {
         log_warnings = false;
      }
      else if (arg == "no_errors") {
         log_errors = false;
      }
      else if (arg == "debug") {
         log_debug = true;
      }
      else if (arg == "log") {
         log = value;
      }
      else if (arg == "state.modelFilter") {
         state.modelFilter = value;
      }
      else if (arg == "gui") {
         gui = true;
      }
      else if (arg == "success") {
         try {
            success_status = atoi(value.c_str());
         }
         catch (exception e) {
            logger.error("parameter success must be of type int");
         }
      }
      else if (arg == "ident") {
         try {
            logger.setIdentSpaces(atoi(value.c_str()));
         }
         catch (exception e) {
            logger.error("parameter ident must be of type int");
         }
      }
      else if (arg == "werror") {
         logger.warningsAsErrors();
      }
   }

   if (log != "") {
      logger.openFile(log);
   }

   logger.setSilent(log_silent);
   logger.displayInfo(log_info);
   logger.displayWarnings(log_warnings);
   logger.displayErrors(log_errors);
   logger.displayDebug(log_debug);

   if (help) {
      display_help(logger);
      exit(0);
   }
   if (usage) {
      display_usage(logger);
      logger.message("");
      display_examples(logger);
      exit(0);
   }
   if (version) {
      display_version(logger);
      exit(0);
   }
   if (gui) {
      //show_gui();
      exit(0);
   }

#ifdef ILIC_NATIVE_REPOSITORY
   bool has_explicit_ili_files = false;
   for (const auto &arg : arguments.getKeys())
      if (arg.find("ilifile") == 0) has_explicit_ili_files = true;
   const ilic::cli::CliRepositoryConfig repository_config =
      ilic::cli::buildRepositoryConfig(arguments);
   if (auto error = ilic::cli::validateRepositoryCliConfig(
      arguments,repository_config,has_explicit_ili_files)) {
      logger.error(*error);
      return 1;
   }
   std::unique_ptr<ilic::RepositoryManager> repository_manager =
      ilic::cli::createRepositoryManager(repository_config);
#endif

   logger.info(get_version_string());

   logger.info("");
   logger.info("loading ili files from command line ...");
   logger.incNestLevel();
   state.context.files().setAutoSearch(!no_auto);
   vector<string> modelDirectories;
   size_t directoryStart = 0;
   while (directoryStart <= ilidirs.size()) {
      size_t separator = ilidirs.find(';',directoryStart);
      string directory = ilidirs.substr(directoryStart,
         separator == string::npos ? string::npos : separator - directoryStart);
      if (!directory.empty()) modelDirectories.push_back(directory);
      if (separator == string::npos) break;
      directoryStart = separator + 1;
   }
   state.context.files().setModelDirectories(std::move(modelDirectories));
#ifdef ILIC_NATIVE_REPOSITORY
   if (repository_manager && !repository_config.requestedModels.empty()) {
      ilic::RepositoryResult resolved = repository_manager->resolve(
         repository_config.requestedModels,repository_config.schemaLanguage);
      ilic::cli::logRepositoryDiagnostics(logger,resolved.diagnostics);
      if (!resolved.success || !ilic::cli::loadResolvedRepositoryModels(state.context.files(),resolved)) return 1;
   }
#endif
   for (auto arg : arguments.getKeys()) {
      string value = arguments.get(arg);
      if (arg.find("ilifile") == 0) {
         logger.info("loading " + value + " ...");
         logger.incNestLevel();
         if (!state.context.files().loadByFile(value)) {
            logger.info("not done.");
            abort(logger,1);
         }
         logger.decNestLevel();
         logger.info("done.");
      }
   }
   logger.decNestLevel();
   logger.info("done.");

   // get interlis version from last file
   if (state.context.files().files().empty()) {
      logger.error("no input .ili files or root models specified");
      return 1;
   }
   string iliversion = state.context.files().files().back()->getIliVersion();

   logger.info("");
   logger.info("loading imported models ...");
   logger.incNestLevel();
   map<string,bool> loaded_models;
   while (true) {
      int fcount = state.context.files().files().size();
      for (IliFile *f : state.context.files().files()) {
         for (string modelname : f->getRequiredModels()) {
            if (loaded_models[modelname]) {
               continue;
            }
            else if (modelname == "INTERLIS") {
               continue;
            }
            logger.info("searching for model " + modelname + " ...");
            logger.incNestLevel();
            IliFile *f = state.context.files().loadByModel(modelname,iliversion);
#ifdef ILIC_NATIVE_REPOSITORY
            if (f == nullptr && repository_manager) {
               const string schema = !repository_config.schemaLanguage.empty()
                  ? repository_config.schemaLanguage : (iliversion == "1.0" ? "ili1" :
                     (iliversion == "2.4" ? "ili2_4" : "ili2_3"));
               ilic::RepositoryResult resolved = repository_manager->resolve(modelname,schema);
               ilic::cli::logRepositoryDiagnostics(logger,resolved.diagnostics);
               if (resolved.success) {
                  ilic::cli::loadResolvedRepositoryModels(state.context.files(),resolved);
                  f = state.context.files().loadByModel(modelname,iliversion);
               }
            }
#endif
            if (f == nullptr) {
               logger.info("not found.");
               logger.decNestLevel();
               continue;
            }
            loaded_models[modelname] = true;
            logger.decNestLevel();
            logger.info("found in " + f->getFilePath() + ".");
         }
      }
      if (fcount == state.context.files().files().size()) {
         break;
      }
      else if (fcount == 100) {
         // something went wrong
         break;
      }
   }
   logger.decNestLevel();
   logger.info("done.");

   logger.info("");
   logger.info("all input files are:");
   for (IliFile *f : state.context.files().files()) {
      string models = "";
      for (string model : f->getModels()) {
         if (models == "") {
            models = model;
         }
         else {
            models += "," + model;
         }
      }
      if (f->getFilePath() == "INTERLIS") {
         continue;
      }
      if (f->getAutoSearch()) {
         logger.info(1,f->getFilePath() + ", iliversion=" + f->getIliVersion() + ", models=" + models + ", auto search");
      }
      else {
         logger.info(1,f->getFilePath() + ", iliversion=" + f->getIliVersion() + ", models=" + models + ", command line");
      }
   }
   logger.info("done.");

   // compile all .ili files
   bool multiple_iliversions = false;
   compile(state,state.context.files().loadByModel("INTERLIS",iliversion));
   int count=0;
   while (true) {
      bool all_compiled = true;
      for (IliFile *f : state.context.files().files()) {
         if (f->getIliVersion() != iliversion && f->getFilePath() != "INTERLIS") {
            multiple_iliversions = true;
         }
         all_compiled = compile(state,f) && all_compiled;
      }
      if (all_compiled) {
         break;
      }
      count++;
      if (count > 20) {
         logger.info("");
         logger.info("the following files do not compile:");
         for (IliFile *f : state.context.files().files()) {
            if (!compile(state,f)) {
               logger.info("   " + f->getFilePath());
            }
         }
         logger.internal_error("endless compile loop");
      }
   }

   check_model_semantics(state.context.models(),logger);
   check_model_translations(state.context.models(),logger);

   // list all models
   logger.info("");
   logger.info("all models are:");
   for (Model *m : state.context.models().models()) {
      logger.info(1, "model " + m->Name + ", iliversion=" + m->iliVersion + ", file=" + m->_ilifile);
   }
   if (multiple_iliversions) {
      logger.error("multiple iliversions found.");
   }
   logger.info("done.");

   if (logger.getErrorCount() == 0) {
      // generate output
      if (imd) {
         generate_imd(state,imd_output,iliversion);
      }
      if (ili1) {
         Model *m;
         if (state.modelFilter == "") {
            m = state.context.models().models().back();
         }
         else {
            for (auto mm : state.context.models().models()) {
               if (mm->Name == state.modelFilter) {
                  m = mm;
                  break;
               }
            }
         }
         generate_ili1(state,ili1_output,m);
      }
      if (ili23) {
         generate_ili23(state,ili23_output);
      }
      if (ili24) {
         generate_ili24(state,ili24_output);
      }
      if (xsd) {
         generate_xsd(state,xsd_output,iliversion);
      }
      if (gml) {
         generate_gml(state,gml_output,iliversion);
      }
   }
   else if (imd || ili1 || ili23 || ili24 || xsd || gml) {
      logger.info("");
      logger.warning("no output generated, because of errors.");
   }

   logger.info("");
   string message = get_program_name() + " completed with";

   if (logger.getErrorCount() == 0) {
      message += " no errors";
   }
   else if (logger.getErrorCount() == 1) {
      message += " 1 error";
   }
   else {
      message += " " + to_string(logger.getErrorCount()) + " errors";
   }

   if (logger.getWarningCount() == 0) {
      message += ", no warnings";
   }
   else if (logger.getWarningCount() == 1) {
      message += ", 1 warning";
   }
   else {
      message += ", " + to_string(logger.getWarningCount()) + " warnings";
   }

   logger.info(message + ".");
   logger.closeFile();

   if (logger.getErrorCount() == 0) {
      return success_status;
   }
   else {
      return 1;
   }

}
